// proc_run - 让 proc 成为当前运行的进程。
//   关中断保证“current、satp、CPU 寄存器”三者一起切换，
//   中途不会被时钟中断打断而看到不一致的状态。
void proc_run(struct proc_struct *proc)
{
    if (proc != current)
    {
        bool intr_flag;
        struct proc_struct *prev = current, *next = proc;
        local_intr_save(intr_flag);
        {
            current = proc;
            // 切换页表：写 satp（Sv39 模式 + 根页表物理页号），写法与 enable_paging 相同。
            // libs/riscv.h 的 lsatp() 是 Sv32 遗留，不能用。
            write_csr(satp, ((uintptr_t)SATP_MODE_SV39 << 60) | (next->pgdir >> RISCV_PGSHIFT));
            flush_tlb();
            switch_to(&(prev->context), &(next->context));
        }
        local_intr_restore(intr_flag);
    }
}

// cpu_idle - idleproc 的主循环：永远不阻塞，只要有人需要运行就调用 schedule 让出 CPU。
void cpu_idle(void)
{
    while (1)
    {
        if (current->need_resched)
        {
            schedule();
        }
    }
}
